#!/usr/bin/env python3
"""
make-results.py -- rebuild the table portion of RESULTS.md from run-output.txt.

Deterministic. Stdlib only.

WHY
    RESULTS.md must contain the study's tables, and every figure in it must have
    come from a real run. Rather than retyping numbers into Markdown -- which is
    how a table silently stops matching the run that produced it -- this script
    slices the tables out of run-output.txt verbatim and appends them under the
    hand-written preamble at the top of RESULTS.md.

    Re-run it after every `py -3 study.py > run-output.txt`.

USAGE
    py -3 make-results.py
    py -3 make-results.py --check     # fail if RESULTS.md is stale

EXIT CODES
    0  RESULTS.md rebuilt (or already current with --check)
    1  --check found RESULTS.md stale
    2  run-output.txt or the preamble is missing
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RUN = os.path.join(HERE, "run-output.txt")
OUT = os.path.join(HERE, "RESULTS.md")
PREAMBLE_MARKER = "<!-- BEGIN TABLES (generated by make-results.py; do not edit below) -->"


def sections(lines):
    """Split the report on its top-level 'N. TITLE' headings.

    A heading may wrap onto a second line (section 8 does), so the '====='
    underline is searched for in the two lines that follow the heading rather
    than required immediately beneath it.
    """
    starts = []
    for i, ln in enumerate(lines):
        s = ln.rstrip("\n")
        if len(s) > 3 and s[0].isdigit() and ". " in s[:4] and not s.startswith("  "):
            if any(lines[j].startswith("=" * 50)
                   for j in range(i + 1, min(i + 3, len(lines)))):
                starts.append(i)
    out = []
    for k, i in enumerate(starts):
        end = starts[k + 1] - 1 if k + 1 < len(starts) else len(lines)
        while end > i and lines[end - 1].strip() == "":
            end -= 1
        title = lines[i].strip()
        j = i + 1
        while j < len(lines) and not lines[j].startswith("=" * 50):
            title += " " + lines[j].strip()
            j += 1
        out.append((title, lines[i:end]))
    return out


def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(newline="\n")
    argv = list(sys.argv[1:] if argv is None else argv)
    check = "--check" in argv

    if not os.path.isfile(RUN) or not os.path.isfile(OUT):
        print("ERROR: need both run-output.txt and RESULTS.md", file=sys.stderr)
        return 2

    with open(RUN, "r", encoding="utf-8") as fh:
        lines = fh.readlines()
    with open(OUT, "r", encoding="utf-8") as fh:
        current = fh.read()

    head = current.split(PREAMBLE_MARKER)[0]
    if PREAMBLE_MARKER not in current:
        print("ERROR: RESULTS.md preamble marker not found", file=sys.stderr)
        return 2

    blocks = []
    blocks.append(head.rstrip("\n") + "\n\n" + PREAMBLE_MARKER + "\n\n")
    for title, body in sections(lines):
        if title.startswith("10."):
            continue
        blocks.append("### %s\n\n```text\n" % title)
        blocks.append("".join(body).rstrip("\n") + "\n")
        blocks.append("```\n\n")

    rebuilt = "".join(blocks).rstrip("\n") + "\n"

    if check:
        if rebuilt == current:
            print("RESULTS.md is current with run-output.txt")
            return 0
        print("RESULTS.md is STALE -- re-run: py -3 make-results.py")
        return 1

    if rebuilt == current:
        print("RESULTS.md already current with run-output.txt (%d lines)"
              % current.count("\n"))
        return 0

    with open(OUT, "w", encoding="utf-8", newline="") as fh:
        fh.write(rebuilt)
    print("rebuilt RESULTS.md from run-output.txt (%d lines, %d sections)"
          % (rebuilt.count("\n"), len(sections(lines))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
