#!/usr/bin/env python3
"""
make-results.py -- slice RESULTS.md out of the real run's stdout.

Stdlib only. It reads run-output.txt (the complete, unedited stdout of
`py -3 study.py`) and handcheck-output.txt, and writes RESULTS.md with every
table pasted verbatim. No number in RESULTS.md is typed by hand, so a table
cannot drift away from the run that produced it.

USAGE
    py -3 make-results.py            # write RESULTS.md
    py -3 make-results.py --check    # exit 1 if RESULTS.md is stale
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RUN = os.path.join(HERE, "run-output.txt")
HAND = os.path.join(HERE, "handcheck-output.txt")
OUT = os.path.join(HERE, "RESULTS.md")

SECTION_RE = re.compile(r"^===== SECTION: (.*?) =====$")
END = "===== END SECTION ====="


# The repo requires LF everywhere. Redirected stdout on Windows would otherwise
# translate every newline to CRLF, which fails the file-format gate.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(newline="\n")

PREAMBLE = """# RESULTS.md -- the all-weather test, every table from a real run

**Generated by `make-results.py` from `run-output.txt`, which is the complete
unedited stdout of `py -3 study.py`. Do not hand-edit this file** -- re-run the
script and regenerate. Every figure below was produced on

* pull date **2026-10-14** (UTC), the same pull as the two sibling studies;
* `data/*.csv`, five PRICE-ONLY daily series (SPY, TLT, GLD, EEM, VIX);
* Python 3.10.11 via `py -3`, stdlib only, no network, no third-party imports.

**Read these four caveats before any number below.**

1. **Sleeve E is not a tradable instrument.** The VIX index cannot be bought.
   Sleeve E's return is the VIX index level change while the rule is long, with
   no roll cost, no ETN fee and no borrow. It is an **upper bound on a signal**,
   not a return anybody could have earned. Section 12, item 1.
2. **Price-only.** No dividends, no distributions, anywhere. TLT's price is
   below its own 2002 starting level (the sibling study measured the multiple at
   0.9561), so the bond sleeve and the always-long comparison are understated.
3. **The book window is 2005-09-02 .. 2026-10-14**, 5,311 trading days, 21.1
   years. It begins when gold's SMA(200) first exists, because the book needs
   all five sleeves. It does **not** cover 1993-2004; sleeve A and sleeve G are
   additionally shown on full history for that reason.
4. **Costs are OFF** everywhere except section 10, exactly as in both sibling
   studies.

The one thing to read first is section 5: the correlation matrix. The prior
regime study found its four sleeves 0.666-0.887 correlated year to year and
concluded they were one bet, not four. This book's sleeves are **-0.629 to
+0.762**, and the six trend-sleeve pairs among A-D are **-0.319 to +0.415**.

Section format is verbatim stdout, unchanged.

"""

APPENDIX_PREAMBLE = """
---

# Appendix A -- `handcheck.py`, verbatim

An independent re-derivation that does **not** import `study.py`: it reads only
`data/*.csv` and `out/*.csv` and re-implements the rules and the book from
scratch. It checks the book day by day, re-derives every BOOK_5 yearly return
two further ways (one of them by hand from the sleeve monthly returns), verifies
the correlation matrix is symmetric with a unit diagonal, and recomputes one
sleeve-year straight from prices.

"""


def read(path):
    if not os.path.isfile(path):
        raise SystemExit("ERROR: missing %s" % path)
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read().splitlines()


def slice_sections(lines):
    out = []
    title = None
    buf = []
    for line in lines:
        m = SECTION_RE.match(line)
        if m:
            title = m.group(1)
            buf = []
            continue
        if line.strip() == END and title is not None:
            out.append((title, buf))
            title = None
            buf = []
            continue
        if title is not None:
            buf.append(line)
    return out


def build():
    run = read(RUN)
    sections = slice_sections(run)
    if not sections:
        raise SystemExit("ERROR: no sections found in %s" % RUN)

    parts = [PREAMBLE]
    parts.append("## Contents\n")
    for i, (title, _body) in enumerate(sections, 1):
        anchor = re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")
        parts.append("%d. [%s](#%s)" % (i, title, anchor))
    parts.append("%d. [Appendix A -- handcheck.py, verbatim](#appendix-a--handcheckpy-verbatim)"
                 % (len(sections) + 1))
    parts.append("")

    for title, body in sections:
        while body and not body[0].strip():
            body.pop(0)
        while body and not body[-1].strip():
            body.pop()
        parts.append("---\n")
        parts.append("## %s\n" % title)
        parts.append("```text")
        parts.extend(body)
        parts.append("```")
        parts.append("")

    parts.append(APPENDIX_PREAMBLE)
    parts.append("```text")
    parts.extend(read(HAND))
    parts.append("```")
    parts.append("")
    return "\n".join(parts)


def main(argv):
    text = build()
    if "--check" in argv:
        if not os.path.isfile(OUT):
            print("STALE: RESULTS.md does not exist")
            return 1
        with open(OUT, "r", encoding="utf-8") as fh:
            cur = fh.read()
        if cur != text:
            print("STALE: RESULTS.md differs from what the run would produce")
            return 1
        print("current: RESULTS.md matches run-output.txt")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote RESULTS.md (%d bytes, %d sections)"
          % (len(text), len(slice_sections(read(RUN)))))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
