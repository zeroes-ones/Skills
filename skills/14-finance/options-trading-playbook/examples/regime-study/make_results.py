#!/usr/bin/env python3
"""make_results.py - assemble RESULTS.md from the captured run.

Every figure in RESULTS.md is sliced out of `run.txt`, the captured stdout of
`py -3 study.py`, so the report can never drift from the run that produced it
and nothing is ever retyped.  The prose around the numbers lives here.

  py -3 make_results.py        # after: py -3 study.py > run.txt
"""
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RUN = io.open(os.path.join(HERE, "run.txt"), encoding="utf-8").read().split("\n")


def sec(start, end, include_start=False):
    """Lines from the first line containing `start` up to the first later line
    containing `end` (exclusive of the end line)."""
    i = next(k for k, l in enumerate(RUN) if start in l)
    if not include_start:
        i += 1
    j = next(k for k, l in enumerate(RUN) if k > i and end in l)
    return "\n".join(RUN[i:j]).rstrip()


