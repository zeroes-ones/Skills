#!/usr/bin/env python3
"""
generate_synthetic_log.py -- build the SYNTHETIC options log for this skill.

Deterministic. Stdlib only. No network. No third-party imports.

WHAT THIS FILE IS
    A seeded generator for `synthetic-options-log.csv`. The CSV is not market
    data, not a backtest and not a result. It is invented so that
    `payoff_check.py --from-log` and the sibling cohort engines have a log whose
    arithmetic a reader can check on paper: two cohorts with round R-multiples,
    an explicit `setup` tag on every row, and an explicit `cost` on every row.

THE TWO INVENTED COHORTS
    `credit-condor-50-2x` -- 40 trades. A four-leg iron condor, $1.00 credit on a
        $5.00 width, so the structural max loss is $400. Managed the popular way:
        take profit at 50% of the credit (+$50.00) and stop at 2x the credit
        (-$200.00, which is the R unit here). 31 wins, 9 losses.
        Realised p = 31/40 = 0.775, avg win = 0.25R, avg loss = 1.00R,
        b = 0.25, E = 0.775*0.25 - 0.225 = -0.03125R gross.
        Cost: 4 legs x 2 tickets x $0.65 = $5.20, i.e. 0.026R.

    `debit-spread-2.5R` -- 40 trades. A two-leg debit spread, $2.00 debit on a
        $10.00 width, so the debit paid ($200.00) is the R unit. Target 2.5R,
        stop at the debit (1R). 14 wins, 26 losses, and the wins exited between
        2.18R and 2.70R rather than all at exactly 2.5R, which is what a real
        scale-out or early exit looks like.
        Realised p = 14/40 = 0.35, avg win = 2.47R, avg loss = 1.00R,
        b = 2.47, E = 0.35*2.47 - 0.65 = 0.2145R gross.
        Cost: 2 legs x 2 tickets x $0.65 = $2.60, i.e. 0.013R.

USAGE
    py -3 generate_synthetic_log.py            # writes synthetic-options-log.csv
    py -3 generate_synthetic_log.py --print    # writes nothing, prints to stdout
"""

import argparse
import random
import sys
from datetime import date, timedelta

SEED = 20261014

# The R unit in dollars for each cohort -- "the money lost when the stop fires".
RISK = 200.0

# Cost per trade in dollars: legs x 2 tickets x $0.65 per contract.
COST_CONDOR = 4 * 2 * 0.65      # 5.20
COST_DEBIT = 2 * 2 * 0.65       # 2.60

# The debit-spread wins, in R. Fourteen values averaging exactly 2.4700R, so the
# realised b is paper-checkable: sum = 34.58, 34.58 / 14 = 2.47.
DEBIT_WINS_R = [2.30, 2.40, 2.45, 2.50, 2.55, 2.60, 2.70,
                2.35, 2.65, 2.45, 2.40, 2.55, 2.50, 2.18]

CONDOR_WINS = 31
CONDOR_LOSSES = 9
CONDOR_WIN_R = 0.25
CONDOR_LOSS_R = -1.00

COHORT_CONDOR = "credit-condor-50-2x"
COHORT_DEBIT = "debit-spread-2.5R"

SYMBOLS = ["SYN-INDX", "SYN-ETF", "SYN-ALPH", "SYN-BETA"]
CONDOR_IV_RANK = [62, 68, 71, 74, 66, 70, 63, 69, 75, 72]
DEBIT_IV_RANK = [21, 24, 28, 19, 26, 23, 30, 22, 25, 27]

HEADER = "\n".join([
    "# PROVENANCE: SYNTHETIC / ILLUSTRATIVE -- invented options log. NOT market data. NOT a backtest. NOT a result. It carries no market information whatsoever and must never be quoted as a finding about any instrument, strategy, volatility regime or period.",
    "# PROVENANCE: generated by examples/logs/generate_synthetic_log.py at fixed seed SEED=%d, stdlib only, byte-identical on every run." % SEED,
    "# PROVENANCE: 80 invented closed option positions across two invented cohorts and four invented symbols; close dates 2025-01-15 .. 2025-06-27.",
    "# PROVENANCE: invented by the skill author so that payoff_check.py --from-log has a log whose arithmetic a reader can check on paper. The two cohorts are chosen to sit on DIFFERENT sides of the break-even line: one profitable corner and one negative corner. That contrast is the point.",
    "# PROVENANCE: pnl is invented currency in units of an invented risk unit (200.00 per trade); it is not dollars earned by anyone. cost is an invented commission estimate at 0.65 per contract per ticket.",
    "# Columns: trade_id,open_date,close_date,pnl,risk,cost,setup,symbol,dte,iv_rank,side",
    "#   pnl  = realised P&L in invented currency for that closed position (may be negative)",
    "#   risk = the planned per-trade risk unit in dollars -- the money lost when the stop fires",
    "#          credit-condor-50-2x : 200.00 = 2x the 100.00 credit, the stop distance",
    "#          debit-spread-2.5R   : 200.00 = the 200.00 debit paid, the stop distance",
    "#   cost = commission + fees + half-spread for that position",
    "#   setup= the cohort tag. This is what makes a kill list possible downstream.",
    "#   dte  = days to expiration at entry; iv_rank = the IV rank at entry, invented",
    "# EXPECTED, HAND-COMPUTED, AND ASSERTED BY scripts/verify-skill.sh",
    "#   credit-condor-50-2x: n=40 wins=31 losses=9 p=31/40=0.7750",
    "#     avg_win=0.25R avg_loss=1.00R b=0.25 E=0.7750*0.25-0.2250=-0.03125R",
    "#     cost=5.20/200=0.0260R  E_net=-0.03125-0.0260=-0.05725R   NEGATIVE CORNER",
    "#   debit-spread-2.5R:   n=40 wins=14 losses=26 p=14/40=0.3500",
    "#     avg_win=34.58/14=2.4700R avg_loss=1.00R b=2.47",
    "#     E=0.3500*2.47-0.6500=0.21450R",
    "#     cost=2.60/200=0.0130R  E_net=0.21450-0.0130=0.20150R     PROFITABLE CORNER",
    "trade_id,open_date,close_date,pnl,risk,cost,setup,symbol,dte,iv_rank,side",
])


def build_rows():
    """Return the CSV body rows, deterministically ordered."""
    rng = random.Random(SEED)

    condor_pnls = [CONDOR_WIN_R * RISK] * CONDOR_WINS + [CONDOR_LOSS_R * RISK] * CONDOR_LOSSES
    debit_pnls = [round(r * RISK, 2) for r in DEBIT_WINS_R] + [-RISK] * 26

    # Shuffle each cohort so the wins and losses are interleaved rather than
    # blocked. Deterministic: the seed is fixed.
    rng.shuffle(condor_pnls)
    rng.shuffle(debit_pnls)

    plan = ([(COHORT_CONDOR, p) for p in condor_pnls]
            + [(COHORT_DEBIT, p) for p in debit_pnls])
    order = list(range(len(plan)))
    rng.shuffle(order)
    plan = [plan[i] for i in order]

    rows = []
    for i, (cohort, pnl) in enumerate(plan, start=1):
        close = date(2025, 1, 15) + timedelta(days=3 * i + (i % 5))
        if cohort == COHORT_CONDOR:
            dte = 30 + (i % 16)
            iv_rank = CONDOR_IV_RANK[i % len(CONDOR_IV_RANK)]
            cost = COST_CONDOR
        else:
            dte = 45 + (i % 21)
            iv_rank = DEBIT_IV_RANK[i % len(DEBIT_IV_RANK)]
            cost = COST_DEBIT
        open_ = close - timedelta(days=dte)
        rows.append(",".join([
            "SYNOPT%03d" % i,
            open_.isoformat(),
            close.isoformat(),
            "%.2f" % pnl,
            "%.2f" % RISK,
            "%.2f" % cost,
            cohort,
            SYMBOLS[i % len(SYMBOLS)],
            str(dte),
            str(iv_rank),
            "long" if cohort == COHORT_DEBIT else "short",
        ]))
    return rows


def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(newline="\n")
    ap = argparse.ArgumentParser(prog="generate_synthetic_log.py",
                                 description="build the SYNTHETIC options log")
    ap.add_argument("--print", action="store_true", dest="to_stdout",
                    help="print to stdout instead of writing the CSV")
    ap.add_argument("--out", default="synthetic-options-log.csv",
                    help="output path (default synthetic-options-log.csv)")
    args = ap.parse_args(argv if argv is not None else sys.argv[1:])

    text = HEADER + "\n" + "\n".join(build_rows()) + "\n"
    if args.to_stdout:
        sys.stdout.write(text)
        return 0
    with open(args.out, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)
    sys.stderr.write("wrote %s (%d trade rows)\n" % (args.out, len(build_rows())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
